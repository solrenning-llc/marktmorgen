// Writes lib/data-families/index.ts, the list of the key-family topic files
// (C2-213, variant B1): lib/data-families.ts joins every topic it lists to its
// own four lists, so a family is added in its topic's own file and two pull
// requests adding families of different topics never edit the same lines. A
// new topic is a new file in lib/data-families/, named by the topic (topicOf),
// then this script again. The folder may hold no topic yet: the index is then
// an empty list, and only the families already in lib/data-families.ts count.
// usage: node scripts/data-families-index.mjs          (writes the index)
//        node scripts/data-families-index.mjs --check  (fails when it is stale)
// tests/data-families-index.test.ts runs the same check in `npm test`.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const TOPICS_DIR = "lib/data-families";
export const INDEX_FILE = `${TOPICS_DIR}/index.ts`;

/** The topic of a family: the first part of its name after "nl:", lowercased, [a-z0-9-] only; "nl:" itself and "nl:*" are "root". */
export function topicOf(family) {
  const rest = family.startsWith("nl:") ? family.slice(3) : family;
  const first = rest.includes(":") ? rest.slice(0, rest.indexOf(":")) : rest;
  if (first === "" || first === "*") return "root";
  return first.toLowerCase().replace(/[^a-z0-9-]/g, "-");
}

/** The topic files' names without ".ts", sorted, the index left out. */
export function topicFiles(root = process.cwd()) {
  return readdirSync(join(root, TOPICS_DIR))
    .filter((name) => name.endsWith(".ts") && name !== "index.ts")
    .map((name) => name.slice(0, -3))
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

const binding = (topic) => `t_${topic.replace(/-/g, "_")}`;

/** The index's whole text for these topics. */
export function indexSource(topics) {
  return [
    "// GENERATED by `node scripts/data-families-index.mjs` from the topic files in this folder.",
    "// Never edit it by hand: a new topic is a new file here, then the script again",
    "// (tests/data-families-index.test.ts fails while this index is stale).",
    'import type { TopicFamilies } from "@/lib/data-family-kinds";',
    ...topics.map((topic) => `import { families as ${binding(topic)} } from "./${topic}";`),
    "",
    "/** Every topic's families, in the order of the files' names. */",
    "export const ALL_TOPICS: readonly TopicFamilies[] = [",
    ...topics.map((topic) => `  ${binding(topic)},`),
    "];",
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const want = indexSource(topicFiles());
  if (process.argv.includes("--check")) {
    let have = "";
    try { have = readFileSync(INDEX_FILE, "utf8"); } catch { /* missing is stale */ }
    if (have !== want) {
      console.error(`${INDEX_FILE} is stale: run node scripts/data-families-index.mjs`);
      process.exit(1);
    }
    console.log(`${INDEX_FILE} is up to date`);
  } else {
    writeFileSync(INDEX_FILE, want);
    console.log(`wrote ${INDEX_FILE}`);
  }
}
