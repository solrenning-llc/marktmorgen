/**
 * docs/contacts-cost.md (457 [EL1], unit 1): how many contacts each plan can
 * really keep, and what keeping them costs, measured with the code.
 */
import { MAX_LEADS, MAX_CONTACT_NAME, MAX_CONTACT_TAGS, MAX_TAG_LENGTH } from "@/lib/contact-rules";
import { contactBytes, type Contact } from "@/lib/contacts";
import { MAX_TITLE_LENGTH } from "@/lib/catalog-rules";
import { DATA_ROOM_BYTES } from "@/lib/store-data-rules";
import { PLAN_TITLES, TIERS, type Tier } from "@/lib/plan";

const ISO = new Date(0).toISOString();
/** lib/contacts.ts keeps at most this many titles and ids a contact. */
const MAX_TITLES = 20;
/** The longest product id lib/product-extras.ts accepts. */
const LONGEST_PRODUCT_ID = 40;

/** A yes from a form, with nothing else: the least a contact can take. */
export function smallestContact(): Contact {
  return { agreed: true, agreedAt: ISO, firstAt: ISO, lastAt: ISO, titles: [], ids: [], source: "free", unsub: false, unsubAt: "", t: "", name: "", tags: [], importedAt: "" };
}

/** Every title, id, name, label and mark at its longest. */
export function largestContact(): Contact {
  return {
    agreed: true, agreedAt: ISO, firstAt: ISO, lastAt: ISO,
    titles: Array.from({ length: MAX_TITLES }, () => "x".repeat(MAX_TITLE_LENGTH)),
    ids: Array.from({ length: MAX_TITLES }, () => "a".repeat(LONGEST_PRODUCT_ID)),
    source: "import", unsub: true, unsubAt: ISO, gone: "complained", t: "f".repeat(40),
    name: "n".repeat(MAX_CONTACT_NAME),
    tags: Array.from({ length: MAX_CONTACT_TAGS }, (_, i) => `${i}`.padEnd(MAX_TAG_LENGTH, "t")),
    importedAt: ISO, clicks: ISO,
  };
}

export type ContactRow = { tier: Tier; roomBytes: number; smallestBytes: number; largestBytes: number; fitSmallest: number; fitLargest: number; realCeiling: number };

export function contactRows(): ContactRow[] {
  const smallestBytes = contactBytes(smallestContact());
  const largestBytes = contactBytes(largestContact());
  return TIERS.map((tier) => {
    const roomBytes = DATA_ROOM_BYTES[tier];
    const fitSmallest = Math.floor(roomBytes / smallestBytes);
    return { tier, roomBytes, smallestBytes, largestBytes, fitSmallest, fitLargest: Math.floor(roomBytes / largestBytes), realCeiling: Math.min(MAX_LEADS, fitSmallest) };
  });
}

const n = (value: number) => value.toLocaleString("en-US");
const mb = (bytes: number) => `${n(bytes)} bytes`;

export function renderContactsCost(): string {
  const rows = contactRows();
  const short = rows.filter((row) => row.realCeiling < MAX_LEADS);
  const table = rows.map((row) => `| ${PLAN_TITLES[row.tier]} | ${mb(row.roomBytes)} | ${n(row.fitSmallest)} | ${n(row.fitLargest)} | ${n(MAX_LEADS)} | **${n(row.realCeiling)}** |`);
  return `# How many contacts each plan can really keep (457 [EL1], unit 1, 11 November 2026)

A measurement, not a change. Nothing here changes a limit, a page, a price or \`MAX_LEADS\`. Generated by \`node scripts/contacts-cost.mjs\` from \`tests/contacts-cost-table.ts\`; \`tests/contacts-cost.test.ts\` fails when the two differ.

Queue item 457 [EL1] asks for the worst-case cost of keeping contacts on each plan. If it fits every plan, the item would take the cap off and say "Unlimited contacts"; if not, it would show each plan's real number.

## Where a contact is kept, and what it costs

- **Every contact is taken from the plan's data room.** That holds for a sign-up, an import, the API and labels (\`needContacts\`, \`lib/contacts.ts\`), and for a buyer an order puts on the list (\`lib/order-data.ts\`). A contact takes its record plus its future unsubscribe link (\`contactBytes\`). When the room is full, the write is refused.
- **The room is already priced full, every day of the month,** in the \`database-storage\` line of \`tests/plan-cost-registry.ts\`. Keeping contacts therefore adds no storage cost of its own, on any plan, monthly or yearly. What a plan keeps after it ends is priced in \`retained-data\`. Sending to contacts is priced by the plan's monthly emails, and reading them for an export by the \`export\` reads, which count up to \`MAX_LEADS\`.

## How many fit

The smallest contact (a yes from a form, nothing else) takes **${n(rows[0].smallestBytes)} bytes**. The largest (every title, label, name and mark at its longest) takes **${n(rows[0].largestBytes)} bytes**. The table assumes the room holds nothing else: no products, pages, orders or courses. So these are the most a plan could ever keep.

| Plan | Data room | Smallest contacts that fit | Largest contacts that fit | MAX_LEADS | Real ceiling |
| --- | --- | --- | --- | --- | --- |
${table.join("\n")}

${short.length
    ? `**On ${short.map((row) => PLAN_TITLES[row.tier]).join(" and ")}, the published ${n(MAX_LEADS)} cannot be reached.** The room fills first, at most at ${short.map((row) => `${n(row.realCeiling)} (${PLAN_TITLES[row.tier]})`).join(" and ")}, and sooner when the store keeps anything else. The home page says "A list of up to ${n(MAX_LEADS)} people" (\`components/home-parts.tsx\`, \`listSizeWords\`). The studio speaks of ${n(MAX_LEADS)} as the most one store holds (\`app/studio/page.tsx\`). Neither says it depends on the plan. That is a published number that does not hold on that plan (VR, item 2). The fix is for the owner to choose ("Depende do dono"):
- show each plan's real number, which lowers the visible figure on that plan, against the owner's rule not to cut a visible limit;
- give that plan a larger room, which has a cost and needs the margin rule (MR) first;
- or say on the page that the figure depends on the plan and the room.`
    : `Every plan's room holds more than the published ${n(MAX_LEADS)}.`}

## "Unlimited contacts"

It cannot be said on any plan. However the cap is set, the data room bounds the list, and the room is finite and priced. Taking \`MAX_LEADS\` off would also raise the export's worst read, which counts contacts up to it. The item's own rule applies: never cut the current ${n(MAX_LEADS)} cap.

## Acessibilidade

A document only: no page, component or email changes. Steps and decisions of the main task: 0 → 0.
`;
}
