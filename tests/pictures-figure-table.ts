/**
 * docs/pictures-figure-proposal.md (507 [SG3], unit 1): a figure of its own
 * for a store's pictures (MM-SA-08), with its worst-case cost, as a PROPOSAL.
 */
import { MAX_IMAGE_BYTES } from "@/lib/product-image";
import { MAX_REVIEW_PHOTO_BYTES } from "@/lib/review-summary";
import { STORE_ALLOWANCES } from "@/lib/store-allowance-rules";
import { MOST_CORRECT_READING, receivingOf } from "@/lib/receiving-costs";
import { PLAN_TITLES, type Tier } from "@/lib/plan";
import { GB, STORAGE_PER_GB } from "./plan-cost-registry";
import { planUnits, roomKept } from "./margin-alignment-table";

const ceilBps = (cents: number, bps: number) => Math.ceil((cents * bps) / 10_000);
const taxOf = (pretax: number) => (pretax > 0 ? ceilBps(pretax, MOST_CORRECT_READING.profitTaxBps) + ceilBps(pretax, MOST_CORRECT_READING.incomingExchangeIofBps) : 0);

export type PictureRow = {
  id: string;
  tier: Tier;
  cycle: "month" | "year";
  figureBytes: number;
  monthUsd: number;
  periodUsd: number;
  netWithoutCents: number;
  netWithCents: number;
};

/** The most pictures a store can add in a month: a studio picture door each studio request, a review photo each buyer action. */
export function monthlyMostBytes(tier: Tier): number {
  return STORE_ALLOWANCES[tier].studio * MAX_IMAGE_BYTES + STORE_ALLOWANCES[tier].buyer * MAX_REVIEW_PHOTO_BYTES;
}

export function pictureRows(): PictureRow[] {
  return planUnits(false).map((unit) => {
    const [tier, cycle] = unit.id.split("-") as [Tier, "month" | "year"];
    const figureBytes = monthlyMostBytes(tier);
    const monthUsd = (figureBytes / GB) * STORAGE_PER_GB;
    const periodUsd = (cycle === "year" ? 12 : 1) * monthUsd;
    const receiving = receivingOf(unit.priceCents, MOST_CORRECT_READING, true);
    const base = receiving.revenueCents - receiving.totalCents - unit.usageCents - roomKept(unit);
    const withPictures = base - Math.ceil(periodUsd * 100);
    return { id: `${tier}-${cycle}`, tier, cycle, figureBytes, monthUsd, periodUsd, netWithoutCents: base - taxOf(base), netWithCents: withPictures - taxOf(withPictures) };
  });
}

const usd = (cents: number) => `$${(cents / 100).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
const dollars = (value: number) => `$${value.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 4 })}`;
const gb = (bytes: number) => `${(bytes / 1_000_000_000).toLocaleString("en-US", { maximumFractionDigits: 2 })} GB`;

export function renderPicturesFigure(): string {
  const rows = pictureRows();
  const monthly = rows.filter((r) => r.cycle === "month");
  const figures = monthly.map((r) => `| ${PLAN_TITLES[r.tier]} | ${STORE_ALLOWANCES[r.tier].studio.toLocaleString("en-US")} | ${STORE_ALLOWANCES[r.tier].buyer.toLocaleString("en-US")} | **${gb(r.figureBytes)}** | ${dollars(r.monthUsd)} |`);
  const nets = rows.map((r) => `| ${PLAN_TITLES[r.tier]} ${r.cycle === "year" ? "yearly" : "monthly"} | ${dollars(r.periodUsd)} | ${usd(r.netWithoutCents)} | ${usd(r.netWithCents)} |`);
  return `# A figure of its own for a store's pictures (PROPOSAL, 507 [SG3], unit 1, 11 November 2026)

**PROPOSAL.** Nothing is built, and nothing changes a limit, a price, a flag or a gate. Generated by \`node scripts/pictures-figure.mjs\` from \`tests/pictures-figure-table.ts\`; \`tests/pictures-figure.test.ts\` fails when the two differ.

## Why

Security audit finding MM-SA-08 (\`docs/security-audit-2026-10-18.md\`): pictures are kept outside the storage figure. That covers a product's, a link's, a page block's, one the AI writer made, an email's and a review's photo. One uploaded and never attached is never swept, and **no line of \`tests/plan-cost-registry.ts\` prices them**. They pile up month after month, so their cost has no ceiling, which fails the margin rule (MR). The owner chose (queue item 507) a figure of their own on each plan, sized so that no plan loses room, and a sweep of pictures attached to nothing, with a notice to the creator and never touching one in use. The item asks for the worst-case cost and a ceiling first. That is this unit.

**What already bounds pictures, and what does not.** Since the audit, the picture door (\`lib/picture-door.ts\`) caps how fast pictures come in:
- \`PICTURE_DOORS_PER_HOUR\` doors an hour;
- at most \`PICTURE_DOOR_MAX\` signed and not yet put on anything.

That bounds the pace, not what is kept. A picture stays in the file store until the store closes, put on something or not, so what a store keeps still grows month after month, and no cost line prices it.

## The proposed figure: the most a store can add in a month

A picture door is a studio request (at most \`MAX_IMAGE_BYTES\`, ${gb(MAX_IMAGE_BYTES)}), and a review's photo is a buyer action (at most \`MAX_REVIEW_PHOTO_BYTES\`, ${gb(MAX_REVIEW_PHOTO_BYTES)}). An email's picture is smaller than a studio picture and is counted as one. So in one month a store can add at most:

| Plan | Studio requests a month | Buyer actions a month | Figure (pictures kept at once) | A month, kept full |
| --- | --- | --- | --- | --- |
${figures.join("\n")}

**No plan loses room it can use in a month.** The figure is everything the plan's own requests could add in one, kept at once. How it would work, in a later unit:
- a place is taken before each picture door is given, and given back when the picture is deleted or the door goes unused for a day, as the community's pictures already work (\`lib/community-picture-rules.ts\`);
- past the figure, a door is refused, exactly as a file past the storage figure is;
- what a store keeps stays bounded, so the month above is its ceiling.

**What it changes for a creator.** Today nothing bounds pictures, so a store could keep years of them. With the figure, a store that already keeps more than one month's most would have a new picture door refused until it deletes some or the sweep takes the unattached ones. How many stores are there today is unknown (nothing on sale yet, so likely none); the unit that builds it measures it first, and the owner decides a larger figure if any store is above it, at its cost here.

## What it costs, and every plan still keeps MR

The figure kept full every day, at the dearest store a file may be in (\`STORAGE_PER_GB\`), is the month's most. A yearly payment pays twelve of them. The plans are taken at their prices in force with every right at its worst month (\`planUnits\`) and the spend floor's room, by TX's reading (IRPF 15%, IOF 0.38%):

| Unit | Pictures' figure, the period | Net without it | Net with it |
| --- | --- | --- | --- |
${nets.join("\n")}

Each keeps a positive net. The new cost line would go into \`tests/plan-cost-registry.ts\` with the figure, in the unit that builds it.

## Later units (not built here)

1. **The figure and its place taken before each door.** It covers a product's, a link's, a page's, the AI writer's, an email's and a review's picture, with its own line in the cost registry and the studio showing how much of it is used.
2. **The sweep of pictures attached to nothing,** after a safe delay. A picture in use (a product, a link, a page, an email kept, a review) is never deleted. The creator is told before, and nothing is deleted when what is attached cannot be read (rule 24).
3. **\`docs/security-audit-2026-10-18.md\`:** MM-SA-08 is marked fixed only once both are built and tested.

## Acessibilidade

A document only: no page, component or email changes. Steps and decisions of the main task: 0 → 0.
`;
}
